import { expect, test } from '@playwright/test'

test('crea una dieta manual, edita comidas y conserva fases independientes al recargar', async ({ page }) => {
  await page.goto('/#/dieta')
  await page.getByRole('button', { name: 'Crear fase', exact: true }).click()
  await page.getByLabel('Nombre de la fase', { exact: true }).fill('Mi primera dieta')
  await page.getByLabel('Nombre de la comida 1', { exact: true }).fill('Desayuno')
  await page.getByLabel('Alimentos y cantidades de la comida 1', { exact: true }).fill('Yogur natural\n40 g de avena')
  await page.getByRole('button', { name: '+ Añadir comida' }).click()
  await page.getByLabel('Nombre de la comida 2', { exact: true }).fill('Cena')
  await page.getByLabel('Alimentos y cantidades de la comida 2', { exact: true }).fill('Tortilla y ensalada')
  await page.getByLabel('Notas de la fase (opcional)').fill('Preparar la avena por la noche')
  await page.getByRole('button', { name: 'Guardar fase', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Fase guardada')
  const view = page.getByRole('region', { name: 'Mi primera dieta', exact: true })
  await expect(view.getByRole('article')).toHaveCount(2)
  await expect(view).toContainText('40 g de avena')
  await page.reload()
  await expect(view).toContainText('Preparar la avena')
  await page.getByRole('button', { name: 'Editar fase', exact: true }).click()
  await page.getByLabel('Alimentos y cantidades de la comida 1', { exact: true }).fill('Yogur natural\n50 g de avena')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Quitar comida 2', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar fase', exact: true }).click()
  await expect(view).toContainText('50 g de avena')
  await expect(view.getByRole('article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Crear fase', exact: true }).click()
  await page.getByLabel('Nombre de la fase', { exact: true }).fill('Otra fase')
  await page.getByLabel('Nombre de la comida 1', { exact: true }).fill('Comida')
  await page.getByLabel('Alimentos y cantidades de la comida 1', { exact: true }).fill('Arroz con verduras')
  await page.getByRole('button', { name: 'Guardar fase', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Otra fase', exact: true })).toBeVisible()
  await page.getByLabel('Consultar fase').selectOption({ label: 'Mi primera dieta' })
  await expect(view).toContainText('50 g de avena')
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('navigation', { name: 'Secciones de dieta' }).getByRole('link', { name: 'Calculadora', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Calcular estimación' })).toBeEnabled()
  await expect(page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Dieta', exact: true })).toHaveAttribute('aria-current', 'page')
})

test('conserva el texto ante fallos y permite cancelar sin guardar', async ({ page }) => {
  await page.goto('/#/dieta')
  await page.getByRole('button', { name: 'Crear fase', exact: true }).click()
  await page.getByLabel('Nombre de la fase', { exact: true }).fill('Mi fase')
  await page.getByLabel('Nombre de la comida 1', { exact: true }).fill('Comida')
  await page.getByLabel('Alimentos y cantidades de la comida 1', { exact: true }).fill('Pasta con verduras')
  await page.evaluate(() => { IDBObjectStore.prototype.put = function () { throw new DOMException('Quota', 'QuotaExceededError') } })
  await page.getByRole('button', { name: 'Guardar fase', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No se pudo guardar')
  await expect(page.getByLabel('Alimentos y cantidades de la comida 1', { exact: true })).toHaveValue('Pasta con verduras')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByText('Tu dieta, escrita a tu manera.', { exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toHaveCount(0)
})
