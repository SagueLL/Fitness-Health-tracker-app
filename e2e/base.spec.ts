import { test, expect } from '@playwright/test'

test('Alpha abre Resumen, separa Registros y mantiene Ajustes vacío', async ({ page }) => {
  await page.goto('/')
  await expect(page).toHaveTitle('Alpha')
  await expect(page.getByRole('link', { name: 'Alpha, inicio' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Resumen', exact: true })).toBeVisible()
  await expect(page.getByRole('group', { name: 'Desliza para cambiar de métrica' })).toBeVisible()
  await expect(page.locator('main select, main input[type=date]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Guardar registro' })).toHaveCount(0)
  const nav = page.getByRole('navigation', { name: 'Navegación principal' })
  await expect(nav.getByRole('link')).toHaveText(['Resumen', 'Registros', 'Dieta', 'Ajustes'])
  await nav.getByRole('link', { name: 'Registros' }).click()
  await expect(page.getByRole('heading', { name: 'Registros', exact: true })).toBeVisible()
  await page.getByLabel('Peso (kg)', { exact: true }).fill('72,5')
  await page.getByText('Objetivos y registro rápido', { exact: true }).click()
  const quick = page.getByRole('region', { name: 'Registro rápido de agua', exact: true })
  const input = quick.getByLabel('Cantidad por pulsación (ml)')
  await expect(input).toHaveValue('250')
  await input.fill('350')
  await quick.getByRole('button', { name: 'Guardar preferencia' }).click()
  await expect(quick.getByRole('status')).toContainText('guardada')
  await expect(page.getByLabel('Peso (kg)', { exact: true })).toHaveValue('72,5')
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  await expect(page.getByRole('region', { name: 'Tu registro diario' }).getByRole('status')).toContainText('Registro guardado')
  await expect(page.getByRole('button', { name: 'Añadir 350 ml de agua' })).toBeEnabled()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Añadir 350 ml de agua' })).toBeEnabled()
  await nav.getByRole('link', { name: 'Ajustes' }).click()
  await expect(page.getByRole('heading', { name: 'Ajustes', exact: true })).toBeVisible()
  await expect(page.getByText('Próximamente', { exact: true })).toBeVisible()
  await expect(page.locator('main input, main select, main textarea, main form')).toHaveCount(0)
  await expect(page.getByText('Objetivos sencillos', { exact: true })).toHaveCount(0)
  await nav.getByRole('link', { name: 'Dieta' }).click()
  await expect(page.getByRole('heading', { name: 'Dieta', exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Secciones de dieta' }).getByRole('link', { name: 'Calculadora' }).click()
  await expect(nav.getByRole('link', { name: 'Dieta' })).toHaveAttribute('aria-current', 'page')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.evaluate(() => getComputedStyle(document.documentElement).colorScheme)).toBe('dark')
})

test('comunica un fallo al guardar la cantidad de agua en Registros', async ({ page }) => {
  await page.goto('/#/registros')
  await page.getByText('Objetivos y registro rápido', { exact: true }).click()
  const quick = page.getByRole('region', { name: 'Registro rápido de agua', exact: true })
  await expect(quick.getByLabel('Cantidad por pulsación (ml)')).toHaveValue('250')
  await page.evaluate(() => {
    IDBObjectStore.prototype.put = function () { throw new DOMException('Quota exceeded', 'QuotaExceededError') }
  })
  await quick.getByRole('button', { name: 'Guardar preferencia' }).click()
  await expect(quick.getByRole('alert')).toContainText('No se pudo guardar')
  await expect(quick.getByRole('status')).toBeEmpty()
})

test('los enlaces históricos siguen abriendo la fecha del registro', async ({ page }) => {
  await page.goto('/#/evolucion')
  await expect(page.getByRole('heading', { name: 'Resumen', exact: true })).toBeVisible()
  await page.goto('/#/?date=2026-01-01')
  await expect(page.getByLabel('Fecha del registro')).toHaveValue('2026-01-01')
  await expect(page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Registros' })).toHaveAttribute('aria-current', 'page')
})
