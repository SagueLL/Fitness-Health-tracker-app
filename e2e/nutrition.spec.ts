import { expect, test, type Page } from '@playwright/test'

async function calculateExample(page: Page) {
  await page.goto('/#/dieta')
  await expect(page.getByRole('button', { name: 'Calcular estimación' })).toBeEnabled()
  await page.getByLabel('Variante de Mifflin–St Jeor').selectOption('male')
  await page.getByLabel('Peso de cálculo (kg)', { exact: true }).fill('100')
  await page.getByLabel('Altura (cm)', { exact: true }).fill('175')
  await page.getByLabel('Edad (años cumplidos)', { exact: true }).fill('40')
  await page.getByLabel('Factor de actividad (PAL)', { exact: true }).fill('1,30')
  await page.getByLabel('Fase nutricional').selectOption('loss')
  await page.getByLabel('Déficit (%)', { exact: true }).fill('15')
  await page.getByLabel('Proteína (g/kg de peso)', { exact: true }).fill('1,8')
  await page.getByRole('button', { name: 'Calcular estimación' }).click()
}

test('calcula, guarda y conserva revisiones y precisión al recargar', async ({ page }) => {
  await calculateExample(page)
  const preview = page.getByRole('region', { name: 'Tu estimación', exact: true })
  await expect(preview).toContainText('≈2.100 kcal')
  await expect(preview).toContainText('180 g')
  await expect(preview).toContainText('80 g')
  await expect(preview).toContainText('165 g')
  await preview.getByText('Ver desglose del cálculo').click()
  await expect(preview).toContainText('≈1.900 kcal')
  await page.getByRole('button', { name: 'Guardar objetivo nutricional' }).click()
  await expect(page.getByRole('status')).toContainText('guardado')
  await page.reload()
  await expect(page.getByRole('region', { name: /Definición · desde/ })).toContainText('≈2.100 kcal')
  await expect(page.getByLabel('Proteína (g/kg de peso)', { exact: true })).toHaveValue('1,8')
  await page.getByLabel('Déficit (%)', { exact: true }).fill('10')
  await page.getByRole('button', { name: 'Calcular estimación' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Guardar objetivo nutricional' }).click()
  await expect(page.getByRole('status')).toContainText('guardado')
  const history = page.getByRole('region', { name: 'Histórico nutricional' })
  await expect(history.locator('.nutrition-history > details')).toHaveCount(2)
  await history.getByText(/revisión 1/).click()
  await expect(history).toContainText('≈2.100 kcal')
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('invalida vistas previas al editar y comunica repartos inviables y fallos de guardado', async ({ page }) => {
  await calculateExample(page)
  await page.getByLabel('Proteína (g/kg de peso)', { exact: true }).fill('20')
  await expect(page.getByRole('button', { name: 'Guardar objetivo nutricional' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Calcular estimación' }).click()
  await expect(page.getByRole('alert')).toContainText('superan las calorías')
  await page.getByLabel('Proteína (g/kg de peso)', { exact: true }).fill('1,8')
  await page.getByRole('button', { name: 'Calcular estimación' }).click()
  await page.evaluate(() => { IDBObjectStore.prototype.add = function () { throw new DOMException('Quota', 'QuotaExceededError') } })
  await page.getByRole('button', { name: 'Guardar objetivo nutricional' }).click()
  await expect(page.getByRole('alert')).toContainText('No se pudo guardar')
  await expect(page.getByRole('region', { name: 'Tu estimación', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Histórico nutricional' })).toHaveCount(0)
})
