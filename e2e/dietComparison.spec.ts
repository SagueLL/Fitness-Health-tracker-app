import { expect, test } from '@playwright/test'

test('duplica, edita y compara sin perder la fase original', async ({ page }) => {
  await page.goto('/#/dieta')
  await page.getByRole('button', { name: 'Crear fase', exact: true }).click()
  await page.getByLabel('Nombre de la fase', { exact: true }).fill('Fase original')
  await page.getByLabel('Nombre de la comida 1', { exact: true }).fill('Desayuno')
  await page.getByLabel('Alimentos y cantidades de la comida 1', { exact: true }).fill('40 g de avena')
  await page.getByRole('button', { name: 'Guardar fase', exact: true }).click()
  await page.getByRole('button', { name: 'Duplicar fase', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Copia guardada')
  await expect(page.getByRole('heading', { name: 'Fase original (copia)', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Comparar fases', exact: true }).click()
  const comparison = page.getByRole('region', { name: 'Comparar fases', exact: true })
  await expect(comparison).toContainText('Las comidas y las notas son iguales')
  await comparison.getByRole('button', { name: 'Cerrar comparación' }).click()
  await page.getByRole('button', { name: 'Editar fase', exact: true }).click()
  await page.getByLabel('Nombre de la fase', { exact: true }).fill('Fase siguiente')
  await page.getByLabel('Nombre de la comida 1', { exact: true }).fill('Desayuno nuevo')
  await page.getByLabel('Alimentos y cantidades de la comida 1', { exact: true }).fill('50 g de avena')
  await page.getByRole('button', { name: '+ Añadir comida' }).click()
  await page.getByLabel('Nombre de la comida 2', { exact: true }).fill('Merienda')
  await page.getByLabel('Alimentos y cantidades de la comida 2', { exact: true }).fill('Una manzana')
  await page.getByLabel('Notas de la fase (opcional)').fill('Nueva nota')
  await page.getByRole('button', { name: 'Guardar fase', exact: true }).click()
  await page.reload()
  await page.getByLabel('Consultar fase').selectOption({ label: 'Fase siguiente' })
  await page.getByRole('button', { name: 'Comparar fases', exact: true }).click()
  await expect(comparison).toContainText('1 añadidas · 0 eliminadas · 1 modificadas')
  await expect(comparison.getByRole('article', { name: 'Desayuno: Modificada' })).toContainText('40 g de avena')
  await expect(comparison.getByRole('article', { name: 'Desayuno: Modificada' })).toContainText('50 g de avena')
  await expect(comparison).toContainText('Nueva nota')
  await comparison.getByRole('button', { name: 'Intercambiar fases' }).click()
  await expect(comparison).toContainText('0 añadidas · 1 eliminadas · 1 modificadas')
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByLabel('Consultar fase').selectOption({ label: 'Fase original' })
  const original = page.getByRole('region', { name: 'Fase original', exact: true })
  await expect(original).toContainText('40 g de avena')
  await expect(original).not.toContainText('50 g de avena')
  await expect(original.getByRole('article')).toHaveCount(1)
})

test('si falla la duplicación no se anuncia éxito ni cambia la fase original', async ({ page }) => {
  await page.goto('/#/dieta')
  await page.getByRole('button', { name: 'Crear fase', exact: true }).click()
  await page.getByLabel('Nombre de la fase', { exact: true }).fill('Mi fase')
  await page.getByLabel('Nombre de la comida 1', { exact: true }).fill('Comida')
  await page.getByLabel('Alimentos y cantidades de la comida 1', { exact: true }).fill('Arroz')
  await page.getByRole('button', { name: 'Guardar fase', exact: true }).click()
  await page.evaluate(() => { IDBObjectStore.prototype.add = function () { throw new DOMException('Quota', 'QuotaExceededError') } })
  await page.getByRole('button', { name: 'Duplicar fase', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No se pudo duplicar')
  await expect(page.getByRole('status')).toHaveCount(0)
  await expect(page.getByLabel('Consultar fase').getByRole('option')).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'Mi fase', exact: true })).toBeVisible()
})
