import { expect, test } from '@playwright/test'

test('registro de fecha pasada, edición, borrado selectivo y agua rápida', async ({ page }) => {
  await page.goto('/#/registros')
  await expect(page.getByRole('button', { name: 'Guardar registro' })).toBeEnabled()
  await page.getByLabel('Fecha del registro').fill('2026-01-01')
  await expect(page.getByRole('button', { name: 'Guardar registro' })).toBeEnabled()
  await page.getByLabel('Agua (ml)', { exact: true }).fill('1000')
  await page.getByLabel('Duración del sueño (min)', { exact: true }).fill('480')
  await page.getByLabel('Puntuación del sueño (0–100)', { exact: true }).fill('85')
  await page.getByLabel('Pasos (pasos)', { exact: true }).fill('0')
  await page.getByLabel('Peso (kg)', { exact: true }).fill('72,5')
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  await expect(page.getByRole('status')).toContainText('Registro guardado')
  await page.reload()
  await page.getByLabel('Fecha del registro').fill('2026-01-01')
  await expect(page.getByLabel('Peso (kg)', { exact: true })).toHaveValue('72,5')
  await expect(page.getByLabel('Pasos (pasos)', { exact: true })).toHaveValue('0')
  await page.getByLabel('Peso (kg)', { exact: true }).fill('72,2')
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  await expect(page.getByRole('status')).toContainText('Registro guardado')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Borrar puntuación del sueño', exact: true }).click()
  await expect(page.getByLabel('Puntuación del sueño (0–100)', { exact: true })).toBeEmpty()
  await expect(page.getByLabel('Duración del sueño (min)', { exact: true })).toHaveValue('480')
  await page.getByRole('button', { name: 'Añadir 250 ml de agua' }).click()
  await expect(page.getByLabel('Agua (ml)', { exact: true })).toHaveValue('1250')
  await page.reload()
  await page.getByLabel('Fecha del registro').fill('2026-01-01')
  await expect(page.getByLabel('Agua (ml)', { exact: true })).toHaveValue('1250')
  await expect(page.getByLabel('Peso (kg)', { exact: true })).toHaveValue('72,2')
  await expect(page.getByLabel('Puntuación del sueño (0–100)', { exact: true })).toBeEmpty()
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('validación, cambios sin guardar y error de almacenamiento', async ({ page }) => {
  await page.goto('/#/registros')
  await expect(page.getByRole('button', { name: 'Guardar registro' })).toBeEnabled()
  await page.getByLabel('Pasos (pasos)', { exact: true }).fill('1,5')
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  await expect(page.getByRole('alert')).toContainText('Revisa pasos')
  await page.getByLabel('Pasos (pasos)', { exact: true }).fill('100')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('navigation').getByRole('link', { name: 'Dieta' }).click()
  await expect(page.getByLabel('Pasos (pasos)', { exact: true })).toHaveValue('100')
  await page.evaluate(() => {
    IDBObjectStore.prototype.put = function () { throw new DOMException('Quota', 'QuotaExceededError') }
  })
  await page.getByRole('button', { name: 'Guardar registro' }).click()
  await expect(page.getByRole('alert')).toContainText('No se pudo guardar')
  await expect(page.getByLabel('Pasos (pasos)', { exact: true })).toHaveValue('100')
  await expect(page.getByRole('status')).toBeEmpty()
})
